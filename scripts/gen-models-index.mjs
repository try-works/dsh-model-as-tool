/**
 * Generate (or check) the repo-level qualification index
 * `verification/models.lock.json` from the per-extension locks.
 *
 * The PER-EXTENSION `packages/*\/models.lock.json` files remain canonical; this
 * script only projects their stable identity fields (package, model, engine,
 * tokenizer, platforms, asset counts) into one index and records the SHA-256 of
 * each source lock so drift in either direction is detectable.
 *
 * Usage:
 *   node scripts/gen-models-index.mjs            write the index (idempotent)
 *   node scripts/gen-models-index.mjs --check    fail when the index is stale
 *
 * `--check` also validates that `verification/compatibility.json` and
 * `verification/quality-gates.json` parse and carry their required keys, so the
 * verification chain fails when any of the three §21.5 artifacts drifts.
 */

import { createHash } from 'node:crypto'
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const packagesDir = join(root, 'packages')
const outPath = join(root, 'verification', 'models.lock.json')

const check = process.argv.includes('--check')
const fail = (message) => {
  console.error(`models-index: ${message}`)
  process.exitCode = 1
}

/** The source locks (canonical), excluding test fixtures. */
const entries = []
for (const pkg of readdirSync(packagesDir).sort()) {
  const lockPath = join(packagesDir, pkg, 'models.lock.json')
  if (!existsSync(lockPath)) continue
  if (pkg === 'dsh-model-as-tool') continue // its models.lock.json lives under tests/fixtures only
  let lock
  try {
    lock = JSON.parse(readFileSync(lockPath, 'utf8'))
  } catch (error) {
    fail(`cannot parse ${lockPath}: ${error instanceof Error ? error.message : String(error)}`)
    continue
  }
  const assetSets = lock['assetSets']
  if (typeof assetSets !== 'object' || assetSets === null) {
    fail(`${lockPath} declares no assetSets`)
    continue
  }
  const sets = {}
  for (const [setId, raw] of Object.entries(assetSets)) {
    const set = raw
    const model = set['model'] ?? {}
    const engine = set['engine'] ?? {}
    const tokenizer = set['tokenizer'] ?? {}
    const assets = Array.isArray(set['assets']) ? set['assets'] : []
    const platforms = Array.isArray(set['platforms']) ? set['platforms'] : []
    sets[setId] = {
      model: {
        provider: typeof model['provider'] === 'string' ? model['provider'] : 'undeclared',
        identity: typeof model['identity'] === 'string' ? model['identity'] : 'undeclared',
        revision: typeof model['revision'] === 'string' ? model['revision'] : 'undeclared',
      },
      engine: {
        kind: typeof engine['kind'] === 'string' ? engine['kind'] : 'undeclared',
        version: typeof engine['version'] === 'string' ? engine['version'] : 'undeclared',
      },
      tokenizer: {
        kind: typeof tokenizer['kind'] === 'string' ? tokenizer['kind'] : 'undeclared',
        identity: typeof tokenizer['identity'] === 'string' ? tokenizer['identity'] : 'undeclared',
      },
      assetCount: assets.length,
      platforms,
    }
  }
  entries.push({
    package: `@try-works/${pkg}`,
    lockPath: join('packages', pkg, 'models.lock.json'),
    lockSha256: createHash('sha256').update(readFileSync(lockPath)).digest('hex'),
    lockVersion: typeof lock['lockVersion'] === 'number' ? lock['lockVersion'] : 'undeclared',
    assetSets: sets,
  })
}

const document = {
  schemaVersion: '1.0.0',
  generatedAt: new Date().toISOString(),
  note: 'GENERATED by scripts/gen-models-index.mjs from the per-extension models.lock.json files, which remain canonical. Do not edit by hand.',
  extensions: entries,
}

if (check) {
  if (!existsSync(outPath)) {
    fail('verification/models.lock.json is missing; run: node scripts/gen-models-index.mjs')
  } else {
    const current = JSON.parse(readFileSync(outPath, 'utf8'))
    const comparable = { ...document, generatedAt: undefined }
    const existing = { ...current, generatedAt: undefined }
    if (JSON.stringify(comparable) !== JSON.stringify(existing)) {
      fail('verification/models.lock.json is stale; run: node scripts/gen-models-index.mjs')
    }
  }
  for (const [label, path, keys] of [
    ['compatibility.json', join(root, 'verification', 'compatibility.json'), ['platform', 'matrix']],
    ['quality-gates.json', join(root, 'verification', 'quality-gates.json'), ['reviewedAt', 'gates']],
  ]) {
    if (!existsSync(path)) {
      fail(`verification/${label} is missing`)
      continue
    }
    let parsed
    try {
      parsed = JSON.parse(readFileSync(path, 'utf8'))
    } catch (error) {
      fail(`verification/${label} is unreadable: ${error instanceof Error ? error.message : String(error)}`)
      continue
    }
    for (const key of keys) {
      if (!(key in parsed)) fail(`verification/${label} is missing the required "${key}" key`)
    }
  }
  console.log('models-index OK — verification/models.lock.json current; compatibility.json and quality-gates.json parse with required keys.')
} else {
  writeFileSync(outPath, `${JSON.stringify(document, null, 2)}\n`)
  console.log(`models-index written: verification/models.lock.json (${entries.length} extension(s))`)
}
