/**
 * Render the browser-half Remote artifact from `remote/spec.mjs`.
 *
 * The client module system serves only a package's `./client` bundle and its
 * package-local chunks, so the contribution the page mounts cannot be imported
 * as the ESM `./remote` artifact. The chunk is this plugin's own script; it
 * embeds the validators and method specs from the shared source instead of
 * keeping a second hand-written copy.
 *
 * Usage:
 *   node packages/dsh-model-as-tool/scripts/gen-remote-artifacts.mjs
 *   node packages/dsh-model-as-tool/scripts/gen-remote-artifacts.mjs --check
 *
 * `--check` compares the committed chunk with the rendered text and exits 1 on
 * drift; `npm run verify` reaches it through tests/remote-typert.test.ts.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import {
  INSTALL_WIRE_METHOD,
  METHOD_SPECS,
  NAMESPACE,
  PACKAGE,
  SERVICE,
  codecForModelToolsValue,
  descriptorsFromModelToolsSpecs,
  parseModelToolsValue,
} from '../remote/spec.mjs'

const PACKAGE_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '..')
/** Committed chunk the plugin's browser half loads. */
export const CHUNK_PATH = join(PACKAGE_DIR, 'client', 'client.model-tools.js')
/** Chunk filename as the client module system resolves it from the entry. */
export const CHUNK_NAME = 'client.model-tools.js'

/**
 * Render the lazy-CJS chunk.
 * @returns the complete script text written to `client/client.model-tools.js`.
 */
export function renderChunk() {
  return `// Generated by scripts/gen-remote-artifacts.mjs from remote/spec.mjs — do not edit.
//
// The package-local chunk the browser half loads with
// require.async('./${CHUNK_NAME}'). It carries the same strict descriptors as
// the ESM ./remote artifact; see remote/spec.mjs for the wire contract.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PACKAGE)},
  chunk: ${JSON.stringify(CHUNK_NAME)},
  factory(require) {
    var module = { exports: {} }
    var exports = module.exports
    Object.defineProperty(exports, Symbol.toStringTag, { value: 'Module' })

    const PACKAGE = ${JSON.stringify(PACKAGE)}
    const SERVICE = ${JSON.stringify(SERVICE)}
    const NAMESPACE = ${JSON.stringify(NAMESPACE)}
    const INSTALL_WIRE_METHOD = ${JSON.stringify(INSTALL_WIRE_METHOD)}

    ${String(parseModelToolsValue)}

    ${String(codecForModelToolsValue)}

    ${String(descriptorsFromModelToolsSpecs)}

    const METHOD_SPECS = ${JSON.stringify(METHOD_SPECS, null, 2)}

    const contribution = {
      package: PACKAGE,
      descriptors: descriptorsFromModelToolsSpecs(PACKAGE, SERVICE, NAMESPACE, METHOD_SPECS),
    }

    /**
     * Mount the contribution in the calling client plugin's fiber.
     * @param ctx - the client Cordis context whose Remote service is available.
     * @returns null when this Host/assembly has no Client Remote service, else
     *   the Remote service and the namespace disposer.
     */
    async function mount(ctx) {
      const remote = typeof ctx?.get === 'function' ? ctx.get('remote') : undefined
      if (remote === undefined || remote === null || typeof remote.$mount !== 'function') return null
      const dispose = await remote.$mount(contribution)
      return { remote, dispose }
    }

    exports.contribution = contribution
    exports.mount = mount
    return module.exports
  },
})
`
}

/**
 * Write or verify the committed chunk.
 * @param check - compare instead of write.
 * @returns true when the committed text already matches.
 */
export function generateRemoteArtifacts(check = false) {
  const rendered = renderChunk()
  const current = (() => {
    try {
      return readFileSync(CHUNK_PATH, 'utf8')
    } catch {
      return undefined
    }
  })()
  if (check) return current === rendered
  writeFileSync(CHUNK_PATH, rendered)
  return true
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const check = process.argv.includes('--check')
  const okay = generateRemoteArtifacts(check)
  if (!okay) {
    console.error(`gen-remote-artifacts: ${CHUNK_PATH} is stale; run node packages/dsh-model-as-tool/scripts/gen-remote-artifacts.mjs`)
    process.exitCode = 1
  } else {
    console.log(check ? 'gen-remote-artifacts: chunk is current' : `gen-remote-artifacts: wrote ${CHUNK_PATH}`)
  }
}
